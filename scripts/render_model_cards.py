"""Renders docs/model_cards/templates/*.md.tmpl into docs/model_cards/*.md.
Every placeholder is replaced by a value read from a committed file. If any placeholder cannot be resolved,
nothing is written and the unresolved ones are listed.
Placeholder forms:
  {{path/to/file.json::key.sub[0].other[name=x]::.4f}}   value from a JSON file (format optional)
  {{path/to/file.csv::[threshold=0.6].coverage::.4f}}      value from a CSV file (each row is a dict)
  {{include::path/to/file.md}}                             the file's text, verbatim
Selectors: [N] list index; [key=value] the list element whose key equals value (numbers compare as numbers)."""
import csv
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TEMPLATES = REPO / "docs" / "model_cards" / "templates"
OUT = REPO / "docs" / "model_cards"
PLACEHOLDER = re.compile(r"\{\{([^{}]+)\}\}")
HEADER = ("<!-- Generated by scripts/render_model_cards.py from docs/model_cards/templates/{name}. "
          "Edit the template, not this file. -->\n\n")
_cache = {}


def load(rel):
    if rel not in _cache:
        p = REPO / rel
        if not p.is_file():
            raise KeyError(f"file not found: {rel}")
        if rel.endswith(".json"):
            _cache[rel] = json.loads(p.read_text(encoding="utf-8"))
        elif rel.endswith(".csv"):
            with open(p, newline="", encoding="utf-8") as fh:
                _cache[rel] = list(csv.DictReader(fh))
        else:
            raise KeyError(f"unsupported file type for a value: {rel}")
    return _cache[rel]


def same(a, b):
    try:
        return float(a) == float(b)
    except (TypeError, ValueError):
        return str(a) == str(b)


def resolve(obj, path):
    for tok in re.findall(r"\[[^\]]*\]|[^.\[\]]+", path):
        if tok.startswith("["):
            sel = tok[1:-1]
            if "=" in sel:
                k, v = sel.split("=", 1)
                hits = [e for e in obj if isinstance(e, dict) and k in e and same(e[k], v)]
                if len(hits) != 1:
                    raise KeyError(f"{tok} matched {len(hits)} elements")
                obj = hits[0]
            else:
                obj = obj[int(sel)]
        else:
            obj = obj[tok]
    return obj


def fill(match):
    parts = [p.strip() for p in match.group(1).split("::")]
    if parts[0] == "include":
        if len(parts) != 2:
            raise KeyError("include needs exactly one file")
        p = REPO / parts[1]
        if not p.is_file():
            raise KeyError(f"file not found: {parts[1]}")
        return p.read_text(encoding="utf-8").strip()
    if len(parts) not in (2, 3):
        raise KeyError("expected FILE::PATH or FILE::PATH::FORMAT")
    value = resolve(load(parts[0]), parts[1])
    if isinstance(value, (dict, list)):
        raise KeyError("the path points to a structure, not a value")
    if len(parts) == 3:
        num = float(value)
        return format(int(num), parts[2]) if parts[2].endswith("d") else format(num, parts[2])
    return str(value)


def main():
    templates = sorted(TEMPLATES.glob("*.md.tmpl"))
    if not templates:
        sys.exit(f"no templates found in {TEMPLATES}")
    errors, rendered = [], {}
    for tmpl in templates:
        def safe(m, tmpl=tmpl):
            try:
                return fill(m)
            except Exception as exc:
                errors.append((tmpl.name, m.group(0), f"{type(exc).__name__}: {exc}"))
                return m.group(0)
        rendered[tmpl] = PLACEHOLDER.sub(safe, tmpl.read_text(encoding="utf-8"))
    if errors:
        print(f"{len(errors)} placeholders could not be resolved. Nothing was written.")
        for name, ph, why in errors:
            print(f"  {name}: {ph}\n      {why}")
        sys.exit(1)
    for tmpl, text in rendered.items():
        dest = OUT / tmpl.name[: -len(".tmpl")]
        with open(dest, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(HEADER.format(name=tmpl.name) + text.strip() + "\n")
        print("wrote", dest.relative_to(REPO))
    print(f"rendered {len(rendered)} cards")


if __name__ == "__main__":
    main()